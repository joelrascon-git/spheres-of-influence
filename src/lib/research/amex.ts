/**
 * The American Express research corpus, encoded as a typed dataset.
 *
 * Source: the seven research documents in `content/research/` (generated Oct 12–13,
 * 2026). Every record keeps the corpus's own confidence labels (Confirmed /
 * Secondhand / Unverified / Inference), its sources, and its cross-references
 * (I1–I14 initiatives, Ch1–Ch16 challenges). Nothing here is invented: when the
 * corpus marks a claim Unverified or conflicting, the record carries that in
 * `gaps` or `confidence` instead of silently resolving it.
 *
 * Initiative codes follow `AmEx - Initiatives.md` (I10 = Marketing AI, I11 = Dining,
 * I12 = Premium refresh, I13 = International). The Key Contacts file numbered
 * I10–I13 differently; those links are translated to the canonical codes here.
 */
import type {
  ChampionFlagValue,
  Confidence,
  DocTypeValue,
  EntityTypeValue,
  OrgFitValue,
  PersonaCode,
  PersonaStatusValue,
  ProgramFitValue,
  ResearchConfidence,
  SeniorityLevelValue,
} from "@/lib/constants";
import type { Evidence, ProgramLink, Source } from "@/lib/types";

// ───────────────────────────── Types ─────────────────────────────

export type ResearchAccount = {
  code: string;
  name: string;
  parent_code: string | null;
  entity_type: EntityTypeValue;
  out_of_scope: boolean;
  /** Domains an imported account may already carry (lowercase). */
  match_domains: string[];
  /** Lowercase names an imported account may already carry. */
  match_names: string[];
  domain: string | null;
  hq: string | null;
  employee_count: number | null;
  description: string | null;
  /** Relationship and significance, from the entity map. */
  notes: string | null;
};

export type ResearchOrg = {
  code: string;
  account_code: string;
  parent_code: string | null;
  name: string;
  aliases: string[];
  description: string | null;
  status: "confirmed" | "inferred";
  factory_fit: OrgFitValue | null;
  buying_role: string | null;
  rank: number | null;
  confidence: ResearchConfidence | null;
  initiative_codes: string[];
  challenge_codes: string[];
  notes: string | null;
};

export type ResearchProgram = {
  code: string;
  name: string;
  summary: string;
  why_it_matters: string | null;
  factory_fit: ProgramFitValue;
  factory_hypothesis: string;
  technologies: string[];
  key_dates: { label: string; date: string }[];
  rank: number;
  confidence: ResearchConfidence;
  sources: Source[];
  org_codes: string[];
  notes: string | null;
};

/** An initiative additionally carries what it is solving for. */
export type ResearchInitiative = ResearchProgram & { solving_for: string | null };

/** A challenge additionally carries its impact and the entity/segment affected. */
export type ResearchChallenge = ResearchProgram & { impact: string | null; entity: string | null };

export type ResearchContact = {
  key: string;
  first_name: string;
  last_name: string;
  title: string | null;
  account_code: string;
  org_code: string | null;
  linkedin_url: string | null;
  location: string | null;
  seniority_level: SeniorityLevelValue | null;
  function_bucket: number | null;
  primary_persona: PersonaCode | null;
  secondary_personas: PersonaCode[];
  persona_status: PersonaStatusValue;
  champion_flag: ChampionFlagValue;
  can_veto: boolean;
  buying_role: string | null;
  evidence: Evidence[];
  gaps: string[];
  is_key: boolean;
  key_reasoning: string | null;
  /** 1–10 from the Key Contacts priority list; null for everyone else. */
  priority_rank: number | null;
  statuses: string[];
  reports_to_key: string | null;
  reports_to_confidence: Confidence | null;
  reports_to_evidence: string | null;
  initiative_links: ProgramLink[];
  challenge_links: ProgramLink[];
  /** Technical career path (Fellow/Distinguished/Principal/Staff): authority override in the score. */
  ic_track: boolean;
  /** Created by research because the person is not in the Evaboot export. */
  not_in_export: boolean;
};

export type ResearchInfluenceEdge = {
  from_key: string;
  to_key: string;
  strength: "high" | "medium" | "low";
  confidence: Confidence;
  evidence: string;
};

export type ResearchDocSpec = {
  key: string;
  title: string;
  doc_type: DocTypeValue;
  scope: "account" | "seller";
  file_name: string;
};

